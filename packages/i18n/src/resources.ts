export const translationResources: TranslationResources = {
  'zh-CN': zhCN,
  'en-US': enUS
};

function flattenKeys(tree: TranslationTree, prefix = ''): string[] {
  return Object.entries(tree).flatMap(([key, value]) => {
    const path = prefix ? `${prefix}.${key}` : key;
    return typeof value === 'string' ? [path] : flattenKeys(value, path);
  });
}

export function validateTranslationParity(): {
  missingInZhCN: string[];
  missingInEnUS: string[];
} {
  const zhKeys = new Set(flattenKeys(zhCN));
  const enKeys = new Set(flattenKeys(enUS));
  return {
    missingInZhCN: [...enKeys].filter((key) => !zhKeys.has(key)),
    missingInEnUS: [...zhKeys].filter((key) => !enKeys.has(key))
  };
}
